"""Shared CLI and per-class process isolation for EPAR experiments."""
import argparse
import json
import os
import subprocess
import sys
from .config import ROOT, STAGES, load_config, resolve_args, validate_inputs


def run_job(args):
    """Run one stage in a fresh process and propagate any failure."""
    validate_inputs(args)
    print(f'[{args.class_name}] {args.stage}', flush=True)
    env = dict(os.environ, PYTHONHASHSEED=str(args.seed))
    subprocess.run([sys.executable, '-m', 'epar.worker'], cwd=ROOT, env=env,
                   input=json.dumps(vars(args)), text=True, check=True)


def main(stage=None):
    """Run a single stage, or all three stages for each configured class."""
    parser = argparse.ArgumentParser(
        description=f'EPAR MVTec 3D-AD: {stage or "class-by-class training and evaluation"}')
    parser.add_argument('--dataset_path', required=True,
                        help='MVTec 3D-AD root, or its parent containing mvtec/')
    cli = parser.parse_args()
    config = load_config()
    stages = (stage,) if stage else STAGES
    jobs = [resolve_args(config, current_stage, cls, cli.dataset_path)
            for cls in config['classes'] for current_stage in stages]
    # Later stages depend on files generated by preceding stages. Check those
    # inputs immediately before execution, not before the pipeline starts.
    for args in jobs:
        run_job(args)
